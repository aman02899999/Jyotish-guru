/**
 * auth.js — admin gate for a static site.
 *
 * SECURITY MODEL — read this before trusting it.
 *
 * This site is static. There is no server, so any check performed here runs on
 * the visitor's machine and can be bypassed by someone who reads the source.
 * The gate is therefore deliberately layered, and only one layer is real:
 *
 *   Layer 1 (deterrent)  Passphrase, verified against a PBKDF2-SHA256 hash.
 *                        No plaintext password exists in the repo. This stops
 *                        casual access and shoulder-surfing. It is NOT a
 *                        cryptographic boundary — a determined visitor can
 *                        edit their own localStorage and see the panel UI.
 *
 *   Layer 2 (real)       Publishing requires a GitHub Personal Access Token
 *                        with `repo` scope. GitHub validates that token
 *                        SERVER-SIDE. Without it, an intruder can only change
 *                        what their own browser displays — they cannot alter
 *                        the live site for anyone else.
 *
 * In short: the passphrase protects the door; the token protects the content.
 * Nothing an attacker does in Layer 1 can affect other visitors.
 *
 * The token is held in sessionStorage (cleared when the tab closes) and is
 * sent only to api.github.com over HTTPS.
 */

const SESSION_KEY = 'ajg-admin-session';
const TOKEN_KEY = 'ajg-admin-token';       // sessionStorage only
const REPO_KEY = 'ajg-admin-repo';
const CONFIG_URL = new URL('../../../admin-config.json', import.meta.url).href;

const PBKDF2_ITERS = 210000;
const SESSION_HOURS = 8;

/* Default credential. Replace it from the panel's Security tab.
 * Passphrase: "jyotish-admin" — CHANGE THIS before going live. */
const FALLBACK = {
  salt: 'YWRpLWp5b3Rpc2gtZGVmYXVsdC1zYWx0',
  hash: null,           // computed lazily from FALLBACK_PHRASE when absent
  iterations: PBKDF2_ITERS,
};
const FALLBACK_PHRASE = 'jyotish-admin';

let config = null;

/* ------------------------------------------------------------------ *
 * Crypto helpers
 * ------------------------------------------------------------------ */

const enc = new TextEncoder();
const b64 = (buf) => btoa(String.fromCharCode(...new Uint8Array(buf)));
const unb64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));

/** PBKDF2-SHA256 → base64. */
export async function derive(passphrase, saltB64, iterations = PBKDF2_ITERS) {
  const key = await crypto.subtle.importKey(
    'raw', enc.encode(passphrase), 'PBKDF2', false, ['deriveBits']
  );
  const bits = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', salt: unb64(saltB64), iterations, hash: 'SHA-256' },
    key, 256
  );
  return b64(bits);
}

export function randomSalt() {
  return b64(crypto.getRandomValues(new Uint8Array(16)));
}

/** Constant-time-ish comparison to avoid trivial timing leaks. */
function safeEqual(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string' || a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

/* ------------------------------------------------------------------ *
 * Config
 * ------------------------------------------------------------------ */

/** Load admin-config.json (committed credential), falling back to the default. */
export async function loadConfig() {
  if (config) return config;
  try {
    const res = await fetch(CONFIG_URL, { cache: 'no-cache' });
    if (res.ok) {
      const j = await res.json();
      if (j && j.salt && j.hash) {
        config = { salt: j.salt, hash: j.hash, iterations: j.iterations || PBKDF2_ITERS };
        return config;
      }
    }
  } catch { /* not deployed yet */ }

  // Derive the default hash once so first-run works with no config file.
  config = {
    ...FALLBACK,
    hash: FALLBACK.hash || await derive(FALLBACK_PHRASE, FALLBACK.salt, FALLBACK.iterations),
    isDefault: true,
  };
  return config;
}

export function usingDefaultCredential() {
  return !!(config && config.isDefault);
}

/** Build a new credential block to paste into admin-config.json. */
export async function makeCredential(passphrase) {
  const salt = randomSalt();
  const hash = await derive(passphrase, salt, PBKDF2_ITERS);
  return { salt, hash, iterations: PBKDF2_ITERS, _note: 'Generated by the admin panel. Commit as admin-config.json.' };
}

/* ------------------------------------------------------------------ *
 * Session
 * ------------------------------------------------------------------ */

/** Verify a passphrase and open a session. */
export async function login(passphrase) {
  const cfg = await loadConfig();
  const got = await derive(passphrase, cfg.salt, cfg.iterations);
  if (!safeEqual(got, cfg.hash)) {
    recordFailure();
    return { ok: false, error: 'Incorrect passphrase.' };
  }
  clearFailures();
  const session = {
    at: Date.now(),
    exp: Date.now() + SESSION_HOURS * 3600_000,
  };
  try { localStorage.setItem(SESSION_KEY, JSON.stringify(session)); } catch { /* quota */ }
  return { ok: true, session };
}

export function isAuthed() {
  try {
    const raw = localStorage.getItem(SESSION_KEY);
    if (!raw) return false;
    const s = JSON.parse(raw);
    if (!s || !s.exp || Date.now() > s.exp) { logout(); return false; }
    return true;
  } catch { return false; }
}

export function sessionExpiry() {
  try {
    const s = JSON.parse(localStorage.getItem(SESSION_KEY) || 'null');
    return s ? new Date(s.exp) : null;
  } catch { return null; }
}

export function logout() {
  try {
    localStorage.removeItem(SESSION_KEY);
    sessionStorage.removeItem(TOKEN_KEY);
  } catch { /* ignore */ }
}

/* ---- rate limiting: slows brute forcing of the local gate ---- */

const FAIL_KEY = 'ajg-admin-fails';

function recordFailure() {
  const f = getFailures();
  f.count += 1;
  f.last = Date.now();
  try { localStorage.setItem(FAIL_KEY, JSON.stringify(f)); } catch { /* ignore */ }
}

function clearFailures() {
  try { localStorage.removeItem(FAIL_KEY); } catch { /* ignore */ }
}

export function getFailures() {
  try { return JSON.parse(localStorage.getItem(FAIL_KEY) || '{"count":0,"last":0}'); }
  catch { return { count: 0, last: 0 }; }
}

/** Seconds the user must wait before the next attempt. */
export function lockoutRemaining() {
  const f = getFailures();
  if (f.count < 3) return 0;
  const waitMs = Math.min(2 ** (f.count - 3) * 5000, 300000); // 5s → 5min
  const left = f.last + waitMs - Date.now();
  return left > 0 ? Math.ceil(left / 1000) : 0;
}

/* ------------------------------------------------------------------ *
 * GitHub token — the real authorisation boundary
 * ------------------------------------------------------------------ */

export function setToken(token, remember = false) {
  try {
    if (remember) localStorage.setItem(TOKEN_KEY, token);
    else sessionStorage.setItem(TOKEN_KEY, token);
  } catch { /* ignore */ }
}

export function getToken() {
  try {
    return sessionStorage.getItem(TOKEN_KEY) || localStorage.getItem(TOKEN_KEY) || '';
  } catch { return ''; }
}

export function clearToken() {
  try {
    sessionStorage.removeItem(TOKEN_KEY);
    localStorage.removeItem(TOKEN_KEY);
  } catch { /* ignore */ }
}

export function hasToken() {
  return !!getToken();
}

export function setRepo(repo) {
  try { localStorage.setItem(REPO_KEY, repo); } catch { /* ignore */ }
}

export function getRepo() {
  try { return localStorage.getItem(REPO_KEY) || 'aman02899999/Jyotish-guru'; }
  catch { return 'aman02899999/Jyotish-guru'; }
}

/** Mask a token for display: ghp_abcd…wxyz */
export function maskToken(t) {
  if (!t) return '';
  if (t.length <= 12) return '•'.repeat(t.length);
  return `${t.slice(0, 7)}…${t.slice(-4)}`;
}
